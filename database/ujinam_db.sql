DROP TABLE IF EXISTS `exam_attempts`;
CREATE TABLE `exam_attempts` (
  `id`               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `exam_id`          BIGINT UNSIGNED NOT NULL,
  `student_id`       BIGINT UNSIGNED NOT NULL,
  `started_at`       DATETIME        NOT NULL,
  `submitted_at`     DATETIME        DEFAULT NULL,
  `expires_at`       DATETIME        NOT NULL,
  `status`           ENUM('not_started','in_progress','submitted','force_logged_out','locked') NOT NULL DEFAULT 'in_progress',
  `score`            FLOAT           DEFAULT NULL,
  `correct_answers`  INT             DEFAULT NULL,
  `wrong_answers`    INT             DEFAULT NULL,
  `violation_count`  INT             NOT NULL DEFAULT 0,
  `force_logged_out` TINYINT(1)      NOT NULL DEFAULT 0,
  `reset_by`         BIGINT UNSIGNED DEFAULT NULL,
  `reset_at`         DATETIME        DEFAULT NULL,
  `created_at`       TIMESTAMP       DEFAULT NULL,
  `updated_at`       TIMESTAMP       DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `exam_attempts_exam_id_foreign` (`exam_id`),
  KEY `exam_attempts_student_id_foreign` (`student_id`),
  KEY `exam_attempts_reset_by_foreign` (`reset_by`),
  CONSTRAINT `exam_attempts_exam_id_foreign` FOREIGN KEY (`exam_id`) REFERENCES `exams` (`id`) ON DELETE CASCADE,
  CONSTRAINT `exam_attempts_student_id_foreign` FOREIGN KEY (`student_id`) REFERENCES `students` (`id`) ON DELETE CASCADE,
  CONSTRAINT `exam_attempts_reset_by_foreign` FOREIGN KEY (`reset_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
